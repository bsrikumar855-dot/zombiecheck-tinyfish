T = date(2026, 11, 15)
D = lambda n: (T - timedelta(days=n)).isoformat()


class FakeTF:
    """Answers fetch() from a dict of url -> result; search returns nothing."""
    def __init__(self, pages): self.pages = pages
    def fetch(self, urls, fmt="html"): return {u: self.pages.get(u, {"error": "page_not_found", "status": 404}) for u in urls}
    def fetch1(self, u, fmt="html"): return self.fetch([u])[u]
    def search(self, *a, **k): return []


def page(url, text, final=None, links=None, **kw):
    return {"url": url, "final_url": final or url, "text": text, "links": links or [], **kw}


def own_ev(signal, age, path="/blog", basis="newest date on page (structured)", host="acme.com"):
    return {"signal": signal, "date": D(age), "url": f"https://{host}{path}", "basis": basis}


def stale_sig(age=800, extra=None, **kw):
    """A live site whose own blog and sitemap are both `age` days old (structured), for the zombie rule."""
    base = {"site_state": "live", "flags": [], "reason_bits": [], "jobs": 0, "signup": "broken", "update": D(age), "release": None,
            "news": None, "social": None, "final_url": "https://acme.com/",
            "evidence": [own_ev("blog", age), own_ev("sitemap", age + 5, "/sitemap.xml", "newest of 4 dated entries")] + (extra or [])}
    return {**base, **kw}


class Detectors(unittest.TestCase):
    def test_parked(self):
        tf = FakeTF({"https://acme.io": page("https://acme.io", "acme.io is for sale! Buy this domain on Sedo.com")})
        s = z.analyze_site(tf, "Acme", "acme.io", T, do_search=False)
        self.assertEqual(s["site_state"], "parked")
        self.assertEqual(z.decide(s, None, T)[0], "zombie")

    def test_redirect_to_unrelated_is_absorbed(self):
        tf = FakeTF({"https://tinyco.com": page("https://tinyco.com", "Enterprise suite " * 50, final="https://bigcorp.com/products")})
        s = z.analyze_site(tf, "TinyCo", "tinyco.com", T, do_search=False)
        self.assertEqual(s["site_state"], "absorbed")
        self.assertEqual(z.decide(s, None, T)[0], "unclear")  # a bare redirect can't tell acquired from renamed
        s["redirect_check"] = {"url": "https://news.example/tinyco-acquired", "snippet": "TinyCo was acquired by BigCorp"}
        self.assertEqual(z.decide(s, None, T)[0], "zombie")

    def test_rebrand_keeps_brand_not_zombie(self):
        tf = FakeTF({"https://zapcorp.com": page("https://zapcorp.com", "Zapcorp is now Zap. Formerly Zapcorp.", final="https://zap.ai/")})
        s = z.analyze_site(tf, "Zapcorp", "zapcorp.com", T, do_search=False)
        self.assertEqual(s["site_state"], "live")
        self.assertTrue(any(f.startswith("moved_to:zap.ai") for f in s["flags"]))

    def test_nav_links_only_in_fetch_links_array(self):
        home = page("https://co.dev", "<h1>Co</h1>", links=["/blog", "https://co.dev/careers", "https://co.dev/signup"])
        tf = FakeTF({"https://co.dev": home,
                     "https://co.dev/blog": page("https://co.dev/blog", f"<p>Launch week {D(10)}</p>"),
                     "https://co.dev/careers": page("https://co.dev/careers", "Open roles", links=["/careers/eng-1", "/careers/eng-2"]),
                     "https://co.dev/signup": page("https://co.dev/signup", '<input type="email">')})
        s = z.analyze_site(tf, "Co", "co.dev", T, do_search=False)
        self.assertEqual(s["update"], D(10))
        self.assertEqual(s["jobs"], 2)
        self.assertEqual(s["signup"], "works")
        self.assertEqual(z.decide(s, None, T)[0], "alive")

    def test_archived_github_repo(self):
        u = "https://github.com/o/oldlib"
        tf = FakeTF({u: page(u, "This repository was archived by the owner on Jan 2, 2023. It is now read-only.")})
        s = z.analyze_site(tf, "oldlib", u, T, do_search=False)
        self.assertEqual(s["site_state"], "archived")
        self.assertEqual(z.decide(s, None, T)[0], "zombie")

    def test_autogenerated_sitemap_ignored(self):
        home = page("https://x.io", "<h1>X</h1>")
        tf = FakeTF({"https://x.io": home, "https://x.io/sitemap.xml": page("https://x.io/sitemap.xml", f"<lastmod>{T}</lastmod><lastmod>{T}</lastmod>")})
        self.assertIsNone(z.analyze_site(tf, "X", "x.io", T, do_search=False)["update"])

    def test_blocked_site_not_penalised_as_dead(self):
        tf = FakeTF({"https://shy.com": {"error": "bot_blocked"}})
        s = z.analyze_site(tf, "Shy", "shy.com", T, do_search=False)
        self.assertEqual(s["site_state"], "blocked")
        v, _, conf, *_ = z.decide(s, None, T)
        self.assertEqual(conf, "low")


